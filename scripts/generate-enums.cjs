// Generates src/proto/enums.ts from the extracted protobuf enum definitions.
const fs = require('node:fs')
const path = require('node:path')

const ENUMS = path.join(__dirname, '..', 'refs', 'proto-enums.json')
const OUT = path.join(__dirname, '..', 'src', 'proto', 'enums.ts')

const enums = JSON.parse(fs.readFileSync(ENUMS, 'utf8'))

/**
 * Maps the extracted qualified names to flat, exported constant names.
 *
 * The first component is the owning message; the second is the enum name.
 */
const WANTED = {
    PlatformType: 'DeviceProps_PlatformType',
    ConnectType: 'ClientPayload_ConnectType',
    ConnectReason: 'ClientPayload_ConnectReason',
    ReleaseChannel: 'ClientPayload_UserAgent_ReleaseChannel',
    Platform: 'ClientPayload_UserAgent_Platform',
    WebSubPlatform: 'ClientPayload_WebInfo_WebSubPlatform',
    AccountType: 'ClientPayload_AccountType',
    TrafficAnonymization: 'ClientPayload_TrafficAnonymization',
    SyncdOperation: 'SyncdMutation_SyncdOperation',
}

/** Finds an enum by its trailing name, ignoring the owner prefix. */
function findByTail(tail) {
    for (const [key, values] of Object.entries(enums)) {
        const parts = key.split('.')
        if (parts[parts.length - 1] === tail) return values
    }
    return null
}

const lines = []
lines.push('/**')
lines.push(' * WhatsApp protocol enumerations.')
lines.push(' *')
lines.push(' * Values are extracted directly from the current WhatsApp wire')
lines.push(' * definitions, so they are byte-compatible with the official clients.')
lines.push(' *')
lines.push(' * Generated by `scripts/generate-enums.cjs` - do not edit by hand.')
lines.push(' */')
lines.push('')

let emitted = 0
for (const [tail, flatName] of Object.entries(WANTED)) {
    const values = findByTail(tail)
    if (!values) {
        console.warn(`enum ${tail} not found`)
        continue
    }
    lines.push(`/** \`${tail}\` enumeration. */`)
    lines.push(`export const ${flatName} = Object.freeze({`)
    for (const [name, value] of Object.entries(values)) {
        lines.push(`    ${name}: ${value},`)
    }
    lines.push('} as const)')
    lines.push('')
    emitted++
}

fs.writeFileSync(OUT, lines.join('\n'))
console.log('emitted enums:', emitted)
